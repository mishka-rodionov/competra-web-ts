export type LegalContentItem = { type: 'p'; text: string } | { type: 'bullets'; items: string[] }

export interface LegalSection {
  title: string
  content: LegalContentItem[]
}

function p(text: string): LegalContentItem {
  return { type: 'p', text }
}

function bullets(...items: string[]): LegalContentItem {
  return { type: 'bullets', items }
}

